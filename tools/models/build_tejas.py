"""
tools/models/build_tejas.py - builds public/models/tejas.glb from the Sketchfab source.

Source: "HAL Tejas" by dimal965, https://sketchfab.com/3d-models/hal-tejas-fd95c85e2452490cbe32f80175498441
(CC BY 4.0). Download its glTF zip into tools/models/source/tejas/ (git-ignored) and unzip it there.

Steps: repaint the base colour (repaint_tejas.py) at full size and resize the texture set to 2K,
then run Blender headless on blender_tejas.py (split, close canopy/airbrakes, hinges, export).
Usage: python -I tools/models/build_tejas.py [path to blender.exe]
"""
import hashlib
import os
import subprocess
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, 'source', 'tejas')
BUILD = os.path.join(SRC, 'build')
OUT = os.path.join(ROOT, 'public', 'models', 'tejas.glb')
VERSION_TS = os.path.join(ROOT, 'src', 'render', 'aircraftModels', 'tejasGlbVersion.ts')
BLENDER = sys.argv[1] if len(sys.argv) > 1 else r'C:\Program Files\Blender Foundation\Blender 4.5\blender.exe'
# Base colour at the source's full 4096 (paint, markings and panel lines are where resolution shows);
# the normal and metal-roughness maps at 2048 (GPU memory on laptops and phones).
SIZE_BASE = 4096
SIZE = 2048
# The paint's finish in the metal-roughness map (glTF: G roughness, B metal): satin, not metallic.
PAINT_ROUGH = 0.62


def main() -> None:
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    tex = os.path.join(SRC, 'textures')
    full = os.path.join(BUILD, 'baseColor_full.png')
    subprocess.run([sys.executable, '-I', os.path.join(HERE, 'repaint_tejas.py'), os.path.join(tex, 'HAL_Tejas_baseColor.png'), full], check=True)
    Image.open(full).resize((SIZE_BASE, SIZE_BASE), Image.LANCZOS).save(os.path.join(BUILD, 'baseColor.png'))
    Image.open(os.path.join(tex, 'HAL_Tejas_normal.png')).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(BUILD, 'normal.png'))
    mr = np.asarray(Image.open(os.path.join(tex, 'HAL_Tejas_metallicRoughness.png')).convert('RGB'), np.float32)
    mask = np.asarray(Image.open(full.rsplit('.', 1)[0] + '_mask.png').resize(mr.shape[1::-1], Image.BILINEAR), np.float32)[:, :, None] / 255.0
    paint = np.array([255.0, PAINT_ROUGH * 255.0, 0.0], np.float32)
    mr = mr * (1.0 - mask) + paint * mask
    Image.fromarray(mr.astype(np.uint8)).resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(BUILD, 'metallicRoughness.png'))
    subprocess.run([BLENDER, '-b', '--factory-startup', '--python', os.path.join(HERE, 'blender_tejas.py'), '--',
                    os.path.join(SRC, 'scene.gltf'), BUILD.replace(os.sep, '/'), OUT], check=True)
    # The GLB's URL carries its content hash, so browsers (and the offline service worker, which
    # serves it cache-first) fetch a rebuilt model instead of a stale copy.
    digest = hashlib.sha256(open(OUT, 'rb').read()).hexdigest()[:12]
    with open(VERSION_TS, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/models/build_tejas.py: the content hash of public/models/tejas.glb.\n')
        f.write(f"export const TEJAS_GLB_HASH = '{digest}';\n")
    print(f'{OUT}: {os.path.getsize(OUT) / 1e6:.2f} MB, hash {digest}')


if __name__ == '__main__':
    main()
