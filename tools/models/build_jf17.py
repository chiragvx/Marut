"""
tools/models/build_jf17.py - builds public/models/jf17.glb from the Sketchfab source.

Source: "JF-17" by dimal965, https://sketchfab.com/3d-models/jf-17-b57660f346314df1877e15b85d6e74be
(CC BY 4.0). Download its glTF zip into tools/models/source/jf17/ (git-ignored) and unzip it there.

Steps: resize the texture set (base colour at the source's 4096, the PAF markings as painted; the
normal and metal-roughness maps to 2048), then run Blender headless on blender_jf17.py (split the
gear, close the canopy, hinges, pylons, export).
Usage: python -I tools/models/build_jf17.py [path to blender.exe] [source dir]
"""
import hashlib
import os
import subprocess
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
BLENDER = sys.argv[1] if len(sys.argv) > 1 else r'C:\Program Files\Blender Foundation\Blender 4.5\blender.exe'
SRC = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, 'source', 'jf17')
BUILD = os.path.join(SRC, 'build')
OUT = os.path.join(ROOT, 'public', 'models', 'jf17.glb')
VERSION_TS = os.path.join(ROOT, 'src', 'render', 'aircraftModels', 'jf17GlbVersion.ts')
SIZE_BASE = 4096
SIZE = 2048


def main() -> None:
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    tex = os.path.join(SRC, 'textures')
    for fn, out, size in (('JF-17_baseColor.png', 'baseColor.png', SIZE_BASE), ('JF-17_normal.png', 'normal.png', SIZE),
                          ('JF-17_metallicRoughness.png', 'metallicRoughness.png', SIZE)):
        Image.open(os.path.join(tex, fn)).convert('RGB').resize((size, size), Image.LANCZOS).save(os.path.join(BUILD, out))
    subprocess.run([BLENDER, '-b', '--factory-startup', '--python', os.path.join(HERE, 'blender_jf17.py'), '--',
                    os.path.join(SRC, 'scene.gltf'), BUILD.replace(os.sep, '/'), OUT], check=True)
    # Content-hashed URL, as the Tejas's (the service worker serves models cache-first).
    digest = hashlib.sha256(open(OUT, 'rb').read()).hexdigest()[:12]
    with open(VERSION_TS, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/models/build_jf17.py: the content hash of public/models/jf17.glb.\n')
        f.write(f"export const JF17_GLB_HASH = '{digest}';\n")
    print(f'{OUT}: {os.path.getsize(OUT) / 1e6:.2f} MB, hash {digest}')


if __name__ == '__main__':
    main()
